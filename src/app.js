import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { rateLimit } from 'express-rate-limit';
import { mkdirSync } from 'node:fs';
import authRouter from './routes/auth.js';
import itemRouter from './routes/items.js';
import claimRouter from './routes/claims.js';
import statsRouter from './routes/stats.js';
import { uploadDir } from './middleware/uploads.js';
import { notFound, errorHandler } from './middleware/errors.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
const origins = (process.env.CLIENT_ORIGIN || 'http://localhost:5173').split(',').map((s) => s.trim());
app.use(cors({ origin(origin, cb) { if (!origin || origins.includes(origin)) cb(null, true); else cb(new Error('Origin not allowed.')); } }));
app.use(express.json({ limit: '100kb' }));
if (process.env.NODE_ENV !== 'test') app.use(morgan('dev'));
mkdirSync(uploadDir, { recursive: true });
app.use('/uploads', express.static(uploadDir, { maxAge: '7d', immutable: true }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', app: 'FindBack API' }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 600, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use('/api/auth', authRouter);
app.use('/api/items', itemRouter);
app.use('/api/claims', claimRouter);
app.use('/api/stats', statsRouter);
app.use(notFound);
app.use(errorHandler);
export default app;
